import { useState } from 'react';
import { X, FileDown, Copy, Check, FileText } from 'lucide-react';
import type { BlastAnalysisResult } from '../types';
import confetti from 'canvas-confetti';

interface ExportReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  result: BlastAnalysisResult | null;
}

export const ExportReportModal: React.FC<ExportReportModalProps> = ({
  isOpen,
  onClose,
  result
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen || !result) return null;

  const markdownContent = `# 🚀 BlastRadius AI - Production Risk & Impact Audit Report
**Target Component**: \`${result.targetNodeLabel}\`
**Analysis Timestamp**: ${result.timestamp}
**Blast Severity**: **${result.severity}** (Impact Score: ${result.blastScore}/100)

---

## 📌 Executive Summary
${result.executiveSummary}

**Proposed Change**:
> ${result.proposedChange}

---

## 📊 Blast Topology Breakdown
- **Direct Impacts (${result.directImpactNodes.length})**: ${result.directImpactNodes.join(', ') || 'None'}
- **Indirect Ripple Risks (${result.indirectImpactNodes.length})**: ${result.indirectImpactNodes.join(', ') || 'None'}
- **Safe Modules (${result.safeNodes.length})**: ${result.safeNodes.join(', ') || 'None'}

---

## 🚨 Breaking Changes & Contract Breaches (${result.breakingChanges.length})
${result.breakingChanges
  .map(
    (b, idx) => `### ${idx + 1}. ${b.title} [${b.severity.toUpperCase()}]
- **Affected File**: \`${b.affectedFile}\`
- **Cause**: ${b.reason}
- **Suggested Resolution**: ${b.suggestedFix}
`
  )
  .join('\n')}

---

## 🛡️ Pre-PR Mitigation Checklist
${result.mitigationSteps
  .map(
    (m) => `- [ ] **${m.title}**
  *Details*: ${m.description}
`
  )
  .join('\n')}

---

## 🧪 Generated Regression Test Suites
${result.generatedTests
  .map(
    (t) => `### \`${t.filename}\` (${t.purpose})
\`\`\`typescript
${t.code}
\`\`\`
`
  )
  .join('\n')}

---
*Generated by BlastRadius AI for Ace Builders Hackathon 2026*
`;

  const handleCopy = () => {
    navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    confetti({ particleCount: 40, spread: 70, origin: { y: 0.7 } });
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `BlastRadius_${result.targetNodeLabel.replace(/\s+/g, '_')}_Audit.md`;
    link.click();
    URL.revokeObjectURL(url);
    confetti({ particleCount: 60, spread: 80, origin: { y: 0.6 } });
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-fade-in">
      <div className="bg-slate-900 border border-slate-700 rounded-2xl w-full max-w-2xl overflow-hidden shadow-2xl flex flex-col max-h-[85vh]">
        {/* Header */}
        <div className="p-4 border-b border-slate-800 flex items-center justify-between bg-slate-950/60">
          <div className="flex items-center gap-2.5">
            <div className="p-2 rounded-lg bg-indigo-950 border border-indigo-700/50 text-indigo-400">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="font-bold text-base text-slate-100">Export Audit Report</h3>
              <p className="text-xs text-slate-400">
                Ready to attach to your Pull Request, Jira issue, or presentation slides.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Markdown Preview */}
        <div className="p-5 flex-1 overflow-y-auto">
          <pre className="p-4 rounded-xl bg-slate-950 border border-slate-800 font-mono text-xs text-slate-300 leading-relaxed overflow-x-auto whitespace-pre-wrap max-h-96">
            {markdownContent}
          </pre>
        </div>

        {/* Footer */}
        <div className="p-4 border-t border-slate-800 flex items-center justify-between bg-slate-950/80">
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-xl text-xs font-medium text-slate-400 hover:text-white transition"
          >
            Close
          </button>
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold border border-slate-700 transition"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-400" /> Copied Markdown!
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" /> Copy Markdown
                </>
              )}
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-5 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-bold shadow-md shadow-indigo-600/30 transition"
            >
              <FileDown className="w-4 h-4" /> Download .md File
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
